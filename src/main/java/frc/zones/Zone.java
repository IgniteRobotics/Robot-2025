package frc.zones;


public class Zone{
    public Double maxSpeed;
    public Integer targetID;
    public Double heading;

    public void setMaxSpeed(double speed){
        maxSpeed = speed;
    }

    public void setTargetID(int id){
        targetID = id;
    }

    public void setHeading(double head){
        heading = head;
    }

}

    

